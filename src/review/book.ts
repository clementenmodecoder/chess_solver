let bookSet: Set<string> | null = null;

/** Position key: placement + side to move + castling (no clocks). */
function key(fen: string): string {
  return fen.split(' ').slice(0, 3).join(' ');
}

function build(): Set<string> {
  const set = new Set<string>();
  for (const line of LINES) {
    const c = new Chess();
    set.add(key(c.fen()));
    for (const san of line.split(' ')) {
      try {
        c.move(san);
      } catch {
        break;
      }
      set.add(key(c.fen()));
    }
  }
  return set;
}

export function isBookPosition(fen: string): boolean {
  if (!bookSet) bookSet = build();
  return bookSet.has(key(fen));
}

export function bookSize(): number {
  if (!bookSet) bookSet = build();
  return bookSet.size;
}
